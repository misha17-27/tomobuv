<?php
/**
 * Проверка правил обрезки SEO-текстов (App\Core\Seo: cutTail, badTail, wordCut) — без базы, только разработка.
 *
 *   php tools/seo-test.php        — «ok N» или список расхождений (код выхода 1)
 *
 * Единица после числа («4» + «пары:36;37») — целым словом: «партия», «парка», «штиблеты» единицей не считаются,
 * число перед ними остаётся («…серия 12» + « партия 2025» → «…серия 12»).
 */
declare(strict_types=1);
require __DIR__ . '/../app/bootstrap.php';

use App\Core\Seo;

$fail = 0;
$n = 0;
$check = static function (string $what, $got, $want) use (&$fail, &$n): void {
    $n++;
    if ($got === $want) return;
    $fail++;
    echo "FAIL $what\n  получено: ", var_export($got, true), "\n  ожидали:  ", var_export($want, true), "\n";
};

// cutTail: [обрезанное, отрезанное, результат]
$tails = [
    // число без единицы — обрывок, снимается
    ['Угги Diana 5825 натур.замша на натур меху бронзовый 4', ' пары:36;37;39;41 РОЗПРОДАЖ', 'Угги Diana 5825 натур.замша на натур меху бронзовый'],
    ['Кроссовки Nike 4', ' пари:36;37', 'Кроссовки Nike'],
    ['Кроссовки Nike 4', ' пар в ящике', 'Кроссовки Nike'],
    ['Сапоги женские Tom.m 12', ' шт. в ящике', 'Сапоги женские Tom.m'],
    ['Кеды Tom.m 12', ' штук в ящике', 'Кеды Tom.m'],
    ['Сапоги модель 12', ' см голенище', 'Сапоги модель'],
    ['Сапоги женские 36', ' р-р', 'Сапоги женские'],
    // слово, которое только начинается на «пар»/«шт», — не единица: число остаётся
    ['Ботинки зимние Tom.m серия 12', ' партия 2025', 'Ботинки зимние Tom.m серия 12'],
    ['Ботинки зимние Tom.m серия 12', ' ПАРТИЯ 2025', 'Ботинки зимние Tom.m серия 12'],
    ['Кроссовки Nike 4', ' парка', 'Кроссовки Nike 4'],
    ['Туфли мужские классика Tom.m 12', ' штиблеты кожа', 'Туфли мужские классика Tom.m 12'],
    ['Черевики Tom.m 12', ' штучне хутро', 'Черевики Tom.m 12'],
    // прочие правила — без изменений
    ['Шлёпанцы РОЗПРОДАЖ 3пари:37;38', ';39', 'Шлёпанцы РОЗПРОДАЖ'],
    ['Ботинки BULL А506 чорний (40-44', '', 'Ботинки BULL А506 чорний'],
    ['Кроссовки "Lian Xin"', ' оптом', 'Кроссовки "Lian Xin"'],
    ['Кроссовки Nike 90', ' оптом', 'Кроссовки Nike 90'],
    ['Туфли (женские) размер 36', '; 37; 38', 'Туфли (женские) размер 36'],
];
foreach ($tails as [$s, $rest, $want]) $check("cutTail «{$s}» + «{$rest}»", Seo::cutTail($s, $rest, 10), $want);

// badTail: обрывок в конце title
$bad = [
    'Угги Diana бронзовий 4 пари:23' => true,
    'Сапоги 5 пар'                   => true,
    'Ботинки BULL чорний (40'        => true,
    'Ботинки Tom.m серия 12'         => true,     // число без единицы в конце
    'Сапоги 4 партии'                => false,    // «партии» — не «пары»
    'Ботинки Tom.m 2 пары:36;37'     => false,    // целый перечень
    'Ботинки Tom.m 47-50'            => false,
];
foreach ($bad as $s => $want) $check("badTail «{$s}»", Seo::badTail($s), $want);

// wordCut: по слову, без обрывка
$check('wordCut партия', Seo::wordCut('Ботинки зимние Tom.m серия 12 партия 2025 года для магазина', 30, 10), 'Ботинки зимние Tom.m серия 12');
$check('wordCut пары', Seo::wordCut('Угги Diana 5825 бронзовый 4 пары:36;37;39;41 РОЗПРОДАЖ', 30, 10), 'Угги Diana 5825 бронзовый');

echo $fail ? "Ошибок: $fail из $n\n" : "ok $n\n";
exit($fail ? 1 : 0);
